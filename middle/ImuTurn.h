#define IMU_TURN_HOLD           2   /* 保持指定航向     */

/* ---- 坐标系 ---- */
/* ---- 方向符号 (重要, 别乱动) ----
 * 电机侧约定: z > 0 = 左轮正转/右轮反转 = 左转(逆时针)。
 * 实测: 命令 +90 时, IMU 报的 yaw 一路往【负】方向跑 (0 -> -130), 说明
 *   **IMU 的 yaw 是"顺时针为正"(罗盘式, 与右手系相反)**, 和驱动方向反着。
 * 所以这里必须是 -1: cur_yaw = -euler[2], 这样 z>0 才会让 cur_yaw 变大(朝目标走)。
 * 屏上显示的 yaw 已按这个符号校正过 -> 屏上 "+" 就是"命令里的正方向"。
 * 【教训】转向方向不对先查这个符号, 不要先去改控制律。 */
#define IMU_TURN_YAW_SIGN      (-1)

/*===========================================================================
 * ★ 原地转向 (TurnDeg) 控制思路 -- v7【按实测角速度预测切断 + 自标定 + 脉冲微调】
 *===========================================================================
 * 为什么不能只靠"固定提前角 + 纯滑行"(v4~v6 的做法):
 *   麦轮原地转**轮子刹不住转向**: 接触点速度落在辊子的自由方向上, 把轮子锁死
 *   辊子照样滚, 所以切断驱动后只能靠地面/辊子阻尼慢慢磨。滑行角有个硬公式:
 *
 *        coast = w^2 / (2a)          w = 切断那一刻的角速度, a = 减速能力
 *
 *   ★ 本车的实测值 (2026-10, 命令 +90 落点 +119 -> 过冲 29 度 反推):
 *        a 约为 145 度/秒^2
 *        => 从最低可控转速(120 PWM 约 113 度/秒)切断就要滑 113^2/(2*145) = 44 度!
 *        => 从全速(170 PWM 约 230 度/秒)切断要滑 180 度 (这就是 v6 能转出 -130 度的原因)
 *     [注] v6 文档里写的 a 约 665 是错的(来自一次符号接反的脏数据), 已按上式更正。
 *     **44 度是这个车"切断后必然要滑"的物理下限, 提前角再调也调不小。**
 *     唯一能减小它的办法: 把切断那一刻的转速降下来 (coast 正比于转速平方)。
 *   所以"提前角"根本不是常数: 它随转速平方变、随地面变、随电量变。
 *   固定给一个数(试过 10 / 15 / 35)必然是这个结果:
 *     - 给小了 -> 从全速切进去 -> 滑几十度, 冲过目标;
 *     - 给大了(= 跳过降速段) -> 干脆没减速, 一样冲过去。
 *   v6 还有个结构 bug: LEAD_DEG 35 与 SLOW_FROM_DEG 35 相等时, 判据
 *   "ad > lead" 先失效, 近段降速分支**整段进不去**, 等于全速切断。
 *
 * v7 怎么做的 (4 段单向状态机, 只往前走, 不回头):
 *   FAR   定速 turn_speed 转          直到"该减速了"
 *   NEAR  降到 min_pwm 低速接近       直到"该切断驱动了"
 *   COAST 断电(Motor_Brake 保轮)等停稳  -> 判落点
 *   PULSE (可选) 停早了, 用 min_pwm 打一个很短的通电脉冲, 再回 COAST
 *
 * 两个门限都由角速度现算, 不是常数:
 *        coast_pred = w^2/(2a) + 盲走补偿 + 余量
 *        "该切断" = 剩余角 <= coast_pred + CUT_MARGIN     ★ 只允许在 NEAR 低速段触发
 *        "该减速" = 剩余角 <= w_fast^2/(2a) + SLOW_MARGIN  ★ 用【满速估计】算, 见下
 *   含义很直白: **"现在松手, 靠惯性正好滑到目标" 的那一刻就松手**。
 *   w 快 -> 公式自动提前切; 地面滑(a 小) -> 公式自动提前切; 电量低 -> 一样自适应。
 *
 *   ★★ "该减速"为什么必须用【满速估计 IMU_TURN_RATE_FAST】算, 不能用本拍实测角速度:
 *     本车 a=145, 满速时 coast = 230^2/(2*145) = 182 度 > 180 度。若拿实测角速度算,
 *     "该减速"要等转速真的升上来才成立 —— 那时车已经转过半个弯, 剩下的角度不够减速,
 *     必然冲过去 (过冲 25 度以上)。按满速估计算, 结果就是:
 *     **90/180 这种小角度转向一开始就直接进 NEAR 低速段, 全程最小 PWM 接近。**
 *     (a 大的车会自动用 FAR: 若 a > 294, 满速 coast 就 < 90 度, 判据才放行 FAR。)
 *   ★★ 同理, 切断判据**只在 NEAR 段才允许触发**: 否则一进 FAR 就会立刻满足
 *     "剩余角 <= coast_pred(182)", 那就是全速切断 -> 滑 180 度。
 *   ★ 代价: 本车 a 小, 所以 90 度转向约 1.0~1.3 秒 (全程 113 度/秒 + 44 度滑行)。
 *     想快只能靠反向出力制动, 但那需要"反着给力矩", 你明确不要, 这里就不做。
 *
 *   盲走补偿: IMU 只有 25Hz(40ms 一帧), 从上一帧到本拍车其实已经多走了 w*dt 度
 *   (全速时 40ms = 9 度!)。这一项必须算进去, 否则每次都会冲过 9 度。
 *
 *   ★★ w 必须量【yaw 的带符号角速度】(本版已改)。v6/v7 用的是 d(|剩余角度|)/dt,
 *   它会在"冲过目标"的那一刻变号, 低通滤波后穿过零点 -> 瞬态假"角速度=0"
 *   -> 连续 8 拍成立 -> **误判停稳** (车还在 100 度/秒以上转, 就是实测那次"停稳了但多转 29 度")。
 *
 *   a (减速能力, 度/秒^2) 不用手调: **每次转完自动标定**。
 *   切断时记下 w 和当时的 yaw, 停稳后量出实际滑行角 coast, 反推:
 *        a = w^2 / (2*coast)     -> 写回 decel_est, 下一次预测就用新值
 *   这是个闭环: 老冲过头 -> 反推的 a 变小 -> 预测滑得更远 -> 自动切得更早。
 *   学习率是**不对称**的: 发现 a 比想的更小(滑更远) -> 立刻采纳(权重 0.7, 防过冲);
 *   发现 a 更大(滑更近) -> 慢慢上修(权重 0.25, 防一次野测值把车带飞)。
 *
 *   最后那几度(纯滑行永远差一点): 用**最小 PWM 通一个很短的时间**去补 ——
 *   关键是"通电时间短到转速还没建立起来", 这样脉冲后附带的滑行也小,
 *   等效于把"转不动的静摩擦下限"拆成比它慢得多的平均转速。
 *   ★ 脉冲时长 = 剩余角的一半 / 脉冲增益 (等比收敛), 增益每次脉冲后按实测自动更新
 *   (增益种子故意给大 -> 脉冲偏短; 只补一半 -> 增益估偏也不会冲过头)。
 *   "瞄短"是故意的: 差一点还能再补一拍, 冲过头就只能收工了 (过冲不可逆)。
 *   ★ 一旦冲过目标就【绝不回转】(脉冲也不给), 直接收工 —— 与 v6 约定一致。
 *
 * 【和参考实现的关系】ROS 的 rotate_recovery / Nav2 的 Spin 用的就是这条:
 *        vel = sqrt(2 * acc_lim * dist_left)  再夹到 [min_rotational_vel, max_rotational_vel]
 *   (默认 max 1.0rad/s=57 度/秒, min 0.4rad/s=23 度/秒, acc_lim 3.2rad/s^2)
 *   本 v7 是它的等价改写: 用实测 w 反推(而不是固定 acc_lim), 用 min_pwm 代替
 *   min_rotational_vel, 再补一个脉冲段对付"开环静摩擦下限太粗"的问题。
 *===========================================================================*/

#define IMU_TURN_SPEED_MAX      170    /* 远段定速 PWM (主速度旋钮)。惯性太大就往下调,
                                        * 注意: 惯性滑行距离正比于转速平方, 调一半 -> 只剩 1/4 */
#define IMU_TURN_MIN_PWM        120    /* 低速接近段 / 脉冲段 PWM = 静摩擦下限。
                                        * 卡着不动就加大; 加大后滑行角也变大(a 会自动跟着适应) */
#define IMU_TURN_SLOW_MARGIN    8.0f   /* "该减速"的余量 (度)。觉得减速太早/太晚就动这个 */
#define IMU_TURN_CUT_MARGIN     4.0f   /* "该切断"的余量 (度)。故意切早一点: 切早了只是差几度
                                        * (下一段脉冲能补回来), 切晚了就是冲过目标(不可逆)。
                                        * 老冲过头 -> 加大(每次 +1); 老差太多 -> 减小 */
#define IMU_TURN_STARTUP_MS     250    /* 起步后这么久内不判"该切断"(防第一帧野值把车直接切停) */
#define IMU_TURN_RATE_FAST     250.0f  /* 满速角速度估计 (度/秒), 只用于 FAR 段判断"该减速了"。
                                        * 取大更保守(更早进低速段), 没坏处 */

/* ---- 自动标定: 减速能力 a (度/秒^2) ---- */
#define IMU_TURN_DECEL_DEF     145.0f  /* ★ a 的种子值 = 本车实测反推值 (2026-10, 命令90落点119) */
#define IMU_TURN_DECEL_MIN       50.0f /* a 的允许范围, 防止野数据把标定带飞 */
#define IMU_TURN_DECEL_MAX     4000.0f
/* ★ 预测用的 a 要打折: 过冲不可逆(冲过就收工), 差一点还能用脉冲补 -> 宁可以为它滑得更远。
 *   0.7 = 按"实际只会滑得更远 40%"来算 -> 提前切。老冲过头就往下调(0.5), 老差太多就往上调(0.85)。
 *   注意: 校准本身不受它影响 (标定出来的还是真实 a), 只有"切点预测"打折。 */
#define IMU_TURN_DECEL_TRUST     0.70f
/* a 的学习率 (不对称): 过冲不可逆, 所以"发现减速比想的更差"要立刻采纳,
 * "发现比想的更好"则慢慢上修 (防一次野测值把车带飞) */
#define IMU_TURN_DECEL_LPF_DOWN 0.70f  /* 实测 a 更小(滑更远)的权重 */
#define IMU_TURN_DECEL_LPF_UP   0.25f  /* 实测 a 更大(滑更近)的权重 */

/* ---- 末段脉冲微调 (把最后几度补上) ---- */
#define IMU_TURN_PULSE_ENABLE      1   /* 1 = 开启 (能进 +-3 度); 0 = 停早了就直接收工 */
#define IMU_TURN_PULSE_MAX         6   /* 一次转向最多补几拍脉冲 (防抖/防没完没了)。
                                        * 每拍约 0.4s, 拍到 6 也就 2.4s, 比冲过目标划算 */
/* ★ 脉冲时长为什么卡在 25~60ms 这么窄:
 *   脉冲"末尾转速"决定它自己带的滑行 (coast = w^2/2a)。按 a=145 估:
 *     25ms -> w 约 32 度/秒 -> 自滑 3.5 度, 这一拍总共走 约 4 度
 *     40ms -> w 约 45 度/秒 -> 自滑 7.0 度, 这一拍总共走 约 8 度
 *     60ms -> w 约 60 度/秒 -> 自滑 12  度, 这一拍总共走 约 14 度
 *   -> 最小可比步进 = 4 度左右, 所以最终精度就是 +-3~4 度 (本车物理极限)。
 *   再想小: 得把通电时间压到 25ms 以下, 但那时转速太小、IMU 25Hz 看不清动了没有。 */
#define IMU_TURN_PULSE_MIN_MS     25   /* 最短通电时间 = 最小可比步进 约 4 度 */
#define IMU_TURN_PULSE_FRAC      0.50f /* ★ 每拍只补【剩余误差的这个比例】(度/度)。
                                        * 一次补满是脆的: 脉冲增益估偏一点就直接冲过目标(不可逆);
                                        * 补一半 -> 误差每拍减半, 增益估偏 2 倍也只是"刚好到位",
                                        * 永远不会冲过头 (代价是多花一两拍, 每拍约 0.4s) */
#define IMU_TURN_PULSE_MAX_MS     60   /* 最长通电时间。★ 别加大: 脉冲末尾转速越高, 它自己带的
                                        * 滑行越大 (滑行正比转速平方), 冲过目标就收工了 */
/* 脉冲增益 (度/毫秒)。★ 种子必须【高估】: 估大了 -> 脉冲给短 -> 差一点(还能再补);
 * 估小了 -> 脉冲给太长 -> 直接冲过目标(不可逆)。实际值约 0.15~0.2, 先给 0.25, 之后自动标 */
#define IMU_TURN_PULSE_GAIN_DEF  0.25f
#define IMU_TURN_PULSE_GAIN_MIN  0.10f
#define IMU_TURN_PULSE_GAIN_MAX  1.00f
/* 脉冲增益的学习率 (不对称): 实测比估计的走得多 -> 赶紧上修(否则下一拍还冲);
 * 实测走得少 -> 慢慢下修(这个方向安全) */
#define IMU_TURN_PULSE_GAIN_UP   0.60f
#define IMU_TURN_PULSE_GAIN_DOWN 0.20f

/* ---- 判据 / 保护 ---- */
#define IMU_TURN_ARRIVE_DEG      4.0f  /* 停稳后落点认到位的窗口 (度)。要更准就收到 2~3 */
#define IMU_TURN_RATE_MAX       400.0f /* 预测用的角速度上限 (夹野值, 防一帧跳变把预测撑爆) */
#define IMU_TURN_RATE_STOP      25.0f  /* 角速度(度/秒)小于它 = 转速已很低, 算"停稳了" */
#define IMU_TURN_RATE_STALE_MS   150   /* 超过这么久没有新的 yaw 帧 = 车没在动, 角速度按 0 算
                                        * (IMU 静止时 yaw 值可能一模一样, 不算这条会卡住不走) */
#define IMU_TURN_ARRIVE_TICKS      8   /* 停稳后连续确认多少拍(5ms) 才认 -> 8 拍 = 40ms */
#define IMU_TURN_ERRWAY_TICKS     40   /* 驱动段却连续这么多拍(40x5ms=200ms)在"远离目标" ->
                                        * 判定方向反了/被顶住, 立即停车 (防白转一大圈) */
#define IMU_TURN_RATE_LPF       0.35f  /* 角速度一阶低通 (0~1, 越小越平滑) */
#define IMU_TURN_TIMEOUT_MS     8000   /* 超时自动停 (0 = 不限时)。含最多 4 拍脉冲的余量 */

/* ---- 保持航向 (HoldAbs) ---- */
